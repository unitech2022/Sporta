/// تنسيق المبالغ للعرض.
///
/// المبالغ تصل من الخادم بكسور (حصة اللاعب = سعر الملعب ÷ عدد اللاعبين)، وكان
/// التطبيق يقرّبها إلى عدد صحيح فيعرض ملعباً بريال واحد على أنه **صفر**. هنا
/// تُعرض كما هي: بلا كسور حين تكون صحيحة، وبمنزلتين حين لا تكون.
String money(num value) {
  final v = value.toDouble();
  if (v == v.roundToDouble()) return v.toStringAsFixed(0);
  // 0.26 تبقى 0.26، و1.50 تصير 1.5 — الصفر الأخير لا يضيف معنى.
  return v.toStringAsFixed(2).replaceFirst(RegExp(r'0$'), '');
}
