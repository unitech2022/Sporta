import 'package:flutter/foundation.dart';

/// Supported application languages.
enum AppLanguage {
  ar,
  en;

  bool get isRtl => this == AppLanguage.ar;
}

/// Central translation table (ported from translations.ts).
/// Feature-specific keys are appended as features are converted.
abstract class AppTranslations {
  static String of(AppLanguage language, String key) {
    final table = language == AppLanguage.ar ? _ar : _en;
    final value = table[key];
    // نص عربي بلا ترجمة كان يظهر عربياً في الواجهة الإنجليزية بصمت؛ في
    // التطوير يُنبَّه عليه مرة لكل مفتاح كي لا يُنسى.
    if (value == null &&
        kDebugMode &&
        language == AppLanguage.en &&
        _arabic.hasMatch(key) &&
        _reportedMissing.add(key)) {
      debugPrint('[i18n] missing English translation: "$key"');
    }
    return value ?? key;
  }

  static final _arabic = RegExp(r'[\u0600-\u06FF]');
  static final Set<String> _reportedMissing = {};

  /// ترجمة قالب فيه متغيرات: المفتاح يحوي عناصر مثل `{n}` تُستبدل بقيم
  /// [params] بعد الترجمة، فيسلم ترتيب الكلمات في اللغتين.
  static String ofArgs(
    AppLanguage language,
    String key,
    Map<String, Object?> params,
  ) {
    var text = of(language, key);
    params.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    return text;
  }

