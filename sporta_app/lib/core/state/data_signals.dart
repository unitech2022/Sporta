import 'package:flutter/foundation.dart';

/// إشارات «تغيّرت بيانات» تعبر الشاشات.
///
/// تبويبات [MainShell] تعيش داخل `IndexedStack`، فالشاشة التي غادرها المستخدم
/// تبقى حيّة بحالتها القديمة: من يضيف ملعباً في تبويب «ملاعبي» يعود إلى لوحة
/// المنشأة فيجدها كما تركها — وهي محمّلة مرة واحدة عند أول بناء. الحل عدّادٌ
/// تزيده الشاشة المُعدِّلة وتسمعه الشاشة المعروضة فتعيد التحميل.
///
/// لا حالة هنا ولا بيانات — مجرد إشارة. من يسمعها يجلب من الـ API بنفسه.
abstract final class DataSignals {
  /// ملاعب المالك وأنديته: إضافة أو تعديل أو حذف.
  static final venues = ValueNotifier<int>(0);

  static void venuesChanged() => venues.value++;
}
