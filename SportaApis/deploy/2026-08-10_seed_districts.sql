--  الإدراج الفعلي — يتخطّى أي حي موجود بنفس الاسم في نفس المدينة
-- ═══════════════════════════════════════════════════════════════════════════
-- أول رقم تسلسلي لكل مدينة، في جدول منفصل: MySQL لا يسمح بذكر جدول مؤقّت
-- مرّتين داخل استعلام واحد.
CREATE TEMPORARY TABLE `tmp_city_base` ENGINE=InnoDB
SELECT `CityAr`, MIN(`Seq`) AS `MinSeq` FROM `tmp_districts` GROUP BY `CityAr`;

INSERT INTO `Districts` (`CityId`, `NameAr`, `NameEn`, `IsActive`, `SortOrder`, `CreatedAt`)
SELECT c.Id,
       t.NameAr,
       t.NameEn,
       1,
       IF(t.Grp = 1, 100, 0) + (t.Seq - m.MinSeq),
       @now
FROM `tmp_districts` t
JOIN `tmp_city_base` m
  ON m.CityAr = t.CityAr
JOIN `Cities` c
  ON c.NameAr = t.CityAr AND c.CountryId = @sa
WHERE NOT EXISTS (
  SELECT 1 FROM `Districts` d WHERE d.CityId = c.Id AND d.NameAr = t.NameAr
);

DROP TEMPORARY TABLE `tmp_districts`;
DROP TEMPORARY TABLE `tmp_city_base`;

-- ── التحقّق: عدد الأحياء بعد التنفيذ ───────────────────────────────────────
SELECT c.Id            AS 'معرّف المدينة',
       c.NameAr        AS 'المدينة',
       c.Region        AS 'المنطقة',
       COUNT(d.Id)     AS 'عدد الأحياء'
FROM `Cities` c
LEFT JOIN `Districts` d ON d.CityId = c.Id AND d.IsActive = 1
WHERE c.CountryId = @sa
GROUP BY c.Id, c.NameAr, c.Region, c.SortOrder
ORDER BY c.SortOrder;
