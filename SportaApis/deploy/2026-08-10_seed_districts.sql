--  أحياء مدن السعودية — تعبئة جدول `Districts`
--
--  الاستخدام:
--      mysql -u root -p SportaDb < 2026-08-10_seed_districts.sql
--
--  ▸ idempotent: كل حي مشروط بعدم وجود اسمه في نفس المدينة، فإعادة التشغيل
--    آمنة ولا تكرّر شيئاً ولا تلمس ما أُضيف يدوياً من لوحة الأدمن.
--  ▸ لا يعتمد على معرّفات ثابتة: يطابق المدن بالاسم العربي داخل السعودية،
--    فيصحّ على أي قاعدة مهما اختلف الترقيم.
--  ▸ المجموعة (1) = ٤١ مدينة كانت بلا أحياء إطلاقاً.
--    المجموعة (2) = أحياء إضافية للمدن الثماني المعبّأة مسبقاً (الرياض، جدة،
--    مكة، المدينة، الدمام، الخبر، الظهران، الأحساء) — تبدأ من SortOrder=100
--    حتى تظهر بعد الأحياء الموجودة لا بينها.
--
--  ⚠ هذه قائمة الأحياء المتداولة والمعروفة لكل مدينة، وليست سجل العناوين
--    الوطني الرسمي (آلاف الأحياء). الأسماء قابلة للتعديل/الحذف من لوحة الأدمن.
-- ═══════════════════════════════════════════════════════════════════════════

SET NAMES utf8mb4;

SET @sa  := (SELECT Id FROM `Countries` WHERE Code = 'SA' LIMIT 1);
SET @now := UTC_TIMESTAMP(6);

SELECT @sa AS 'معرّف السعودية',
       IF(@sa IS NULL, '⚠ طبّق مايجريشن الدول أولاً', 'جاهز') AS 'الحالة';

DROP TEMPORARY TABLE IF EXISTS `tmp_districts`;
DROP TEMPORARY TABLE IF EXISTS `tmp_city_base`;
-- المفتاح الفريد يمنع تكرار حي داخل نفس المدينة لو تكرّر سهواً في القوائم أدناه
-- (بادئة ٦٠ حرفاً لتفادي حدّ ٧٦٧ بايت في إصدارات MySQL القديمة).
CREATE TEMPORARY TABLE `tmp_districts` (
  `Seq`    INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Grp`    TINYINT      NOT NULL,   -- 0 = مدينة بلا أحياء · 1 = إضافة لمدينة معبّأة
  `CityAr` VARCHAR(120) NOT NULL,
  `NameAr` VARCHAR(120) NOT NULL,
  `NameEn` VARCHAR(120) NOT NULL,
  UNIQUE KEY `UQ_tmp_city_name` (`CityAr`(60), `NameAr`(60))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

