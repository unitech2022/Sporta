namespace SportaApis.Enums;

/// <summary>
/// الغرض من رمز التحقق. يُثبَّت وقت الإرسال ويُطابَق وقت التحقق، فرمزٌ طُلب
/// لتسجيل الدخول لا يصلح لحذف الحساب. كل غرض له شرط مسبق مختلف على وجود الرقم
/// في القاعدة، ويُفرض في <c>OtpService</c> قبل صرف أي رصيد لدى المزوّد.
/// </summary>
public enum OtpPurpose
{
    /// <summary>دخول حساب قائم — يشترط أن يكون الرقم مسجّلاً.</summary>
    Login = 0,

    /// <summary>تسجيل حساب جديد — يشترط ألّا يكون الرقم مسجّلاً.</summary>
    Register = 1,

    /// <summary>استعادة كلمة سر حساب أدمن/موظف — يشترط أن يكون الرقم مسجّلاً.</summary>
    ResetPassword = 2,

    /// <summary>تأكيد حذف الحساب — يشترط أن يكون الرقم مسجّلاً.</summary>
    DeleteAccount = 3,

    /// <summary>تأكيد رقم جوال جديد قبل اعتماده في الملف الشخصي.</summary>
    ChangePhone = 4,
}
